// Live Search API using Vercel Serverless Function Proxy (/api/suggest)
export async function searchMovies(query) {
  if (!query || query.trim().length < 2) return [];

  try {
    const res = await fetch(`/api/suggest?q=${encodeURIComponent(query.trim())}`);
    if (res.ok) {
      const data = await res.json();
      if (data && data.results && data.results.length > 0) {
        return data.results;
      }
    }
  } catch (err) {
    console.warn("Backend search proxy unreachable, using local index fallback:", err);
  }

  // Resilient fallback across all curated local titles
  const allCurated = [INITIAL_FEATURED, ...POPULAR_ROWS.flatMap(r => r.items)];
  const qLower = query.toLowerCase().trim();
  return allCurated.filter(m => m.title.toLowerCase().includes(qLower));
}
