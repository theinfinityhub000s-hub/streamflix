// Search API with live suggest & Vega index integration
export async function searchMovies(query) {
  if (!query || query.trim().length < 2) return [];

  try {
    // 1. Try local/suggest proxy
    const res = await fetch(`https://api2new.imdb4.shop/suggest.php?q=${encodeURIComponent(query)}`);
    if (res.ok) {
      const data = await res.json();
      if (data && data.results && data.results.length > 0) {
        return data.results.map(item => ({
          id: item.id || Math.floor(Math.random() * 1000000),
          imdb_id: item.imdb_id || "",
          title: item.title,
          backdrop_path: item.backdrop_path || item.poster_path || "https://image.tmdb.org/t/p/original/xOMo8BRK7PfcJv9JCnx7s5200bm.jpg",
          poster_path: item.poster_path || item.backdrop_path || "https://image.tmdb.org/t/p/w500/1pdfLvkbY9ohJlCjQH2CZjjYVvJ.jpg",
          vote_average: item.vote_average ? Number(item.vote_average).toFixed(1) : "7.2",
          release_date: item.release_date || "2024",
          quality: "HD",
          duration: "2h",
          audio: "Hindi + English",
          genres: ["Movie", "Drama"],
          overview: item.overview || `Watch and download ${item.title} in full HD and 4K quality with Hindi dual audio.`
        }));
      }
    }
  } catch (err) {
    console.warn("Suggest API fallback:", err);
  }

  // Filter local rows if network fails
  const allLocal = [INITIAL_FEATURED, ...POPULAR_ROWS.flatMap(r => r.items)];
  return allLocal.filter(m => m.title.toLowerCase().includes(query.toLowerCase()));
}
