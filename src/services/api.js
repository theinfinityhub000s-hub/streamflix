// Streaming Providers Fleet
export function getStreamingUrls(movie, server = 1) {
  const tmdbId = movie.id || 533535;
  const imdbId = movie.imdb_id || "";

  switch (server) {
    case 1:
      // 2Embed (4K Fast Player)
      return `https://www.2embed.cc/embed/movie/${tmdbId}`;
    case 2:
      // AutoEmbed Player
      return `https://player.autoembed.cc/embed/movie/${tmdbId}`;
    case 3:
      // VidSrc
      return imdbId ? `https://vidsrc.me/embed/movie?imdb=${imdbId}` : `https://vidsrc.to/embed/movie/${tmdbId}`;
    default:
      return `https://www.2embed.cc/embed/movie/${tmdbId}`;
  }
}

